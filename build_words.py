def normalize(word):
    return word.strip()

def build():
    common_set = set()
    for w in COMMON:
        w = normalize(w)
        if is_valid_5letter(w):
            common_set.add(w)

    all_set = set(common_set)
    for w in EXTRA:
        w = normalize(w)
        if is_valid_5letter(w):
            all_set.add(w)

    entries = []
    for w in sorted(all_set):
        entries.append({"word": w, "common": w in common_set})

    return entries

if __name__ == "__main__":
    entries = build()
    print(f"Total valid 5-letter words: {len(entries)}")
    print(f"Common tier: {sum(1 for e in entries if e['common'])}")
    with open("public/words.json", "w", encoding="utf-8") as f:
        json.dump(entries, f, ensure_ascii=False, indent=0)
    print("Wrote public/words.json")
